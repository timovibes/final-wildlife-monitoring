const axios = require('axios');
const autocannon = require('autocannon');
require('dotenv').config();

/**
 * Load Test: POST /api/sightings
 *
 * Simulates 500 rangers submitting sightings concurrently, sustained
 * for 30 seconds. Runs against the REAL dev database (via seeded
 * ranger account) — not the isolated test database — since this is
 * meant to reflect real-world load, not correctness testing.
 *
 * Run: node tests/load/sightings-load-test.js
 * (run this inside the backend container: docker compose exec backend node tests/load/sightings-load-test.js)
 */

const BASE_URL = 'http://localhost:5000';

const run = async () => {
  console.log('Logging in as seeded ranger account...');
  const loginRes = await axios.post(`${BASE_URL}/api/auth/login`, {
    email: 'ranger@wildlife.com',
    password: 'Ranger123!'
  });
  const token = loginRes.data.data.token;
  console.log('✓ Got auth token\n');

  console.log('Fetching a real species ID to attach sightings to...');
  const speciesRes = await axios.get(`${BASE_URL}/api/species`, {
    headers: { Authorization: `Bearer ${token}` }
  });
  const speciesId = speciesRes.data.data.species[0].id;
  console.log(`✓ Using species: ${speciesRes.data.data.species[0].commonName}\n`);

  console.log('Starting load test: 500 concurrent connections, 30 seconds...\n');

  const result = await autocannon({
    url: `${BASE_URL}/api/sightings`,
    method: 'POST',
    connections: 500,
    duration: 30,
    headers: {
      'Content-Type': 'application/json',
      Authorization: `Bearer ${token}`
    },
    body: JSON.stringify({
      speciesId,
      count: 1,
      latitude: -1.2921,
      longitude: 36.8219,
      location: 'Load test location',
      behavior: 'Load test',
      notes: 'Generated by stress test',
      weather: 'Clear'
    })
  });

  console.log('\n═══════════════════════════════════════');
  console.log('  LOAD TEST RESULTS');
  console.log('═══════════════════════════════════════');
  console.log(`Requests/sec (avg):  ${result.requests.average}`);
  console.log(`Latency avg:         ${result.latency.average} ms`);
  console.log(`Latency p99:         ${result.latency.p99} ms`);
  console.log(`Total requests:      ${result.requests.total}`);
  console.log(`2xx responses:       ${result['2xx'] || 0}`);
  console.log(`Non-2xx responses:   ${result.non2xx || 0}`);
  console.log(`Errors:              ${result.errors}`);
  console.log(`Timeouts:            ${result.timeouts}`);
  console.log('═══════════════════════════════════════\n');
};

run().catch((err) => {
  console.error('Load test failed:', err.message);
  process.exit(1);
});